# Write  a  Python  program  to  create  a  set,  add  member(s)  in  a  set  and  remove  one item from set.

# Set creation
yash = {12,13,14,15,16}
print("Original Set members: ",yash)

# adding members
yash.add(50)
print("By adding 50: ",yash)

# Removing member
yash.discard(14)
print("By removing 14: ",yash)